/* Shared by the laptop scripts: the maps on disk, the guide's bundles (live site or a local build), a KV-shaped store
   in a folder, and an R2-shaped archive in a folder. */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

export const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
export const MAPS_DIR = path.join(ROOT, 'maps');

export function loadMaps(ids = []) {
  const all = fs.readdirSync(MAPS_DIR).filter((f) => f.endsWith('.json')).sort().map((f) => JSON.parse(fs.readFileSync(path.join(MAPS_DIR, f), 'utf8')));
  return ids.length ? all.filter((m) => ids.includes(m.id)) : all;
}

export function writeMap(map) {
  fs.writeFileSync(path.join(MAPS_DIR, `${map.id}.json`), `${JSON.stringify(map, null, 2)}\n`);
}

/* src/maps.gen.js: every map inlined, so the Worker bundles them with no JSON-import syntax. */
export function writeIndex(maps) {
  const body = `/* Generated by bin/map-check.mjs --write from maps/*.json. Don't edit by hand. */\nexport const MAPS = ${JSON.stringify(maps, null, 2)};\n`;
  fs.writeFileSync(path.join(ROOT, 'src', 'maps.gen.js'), body);
}

/* The guide's bundles: `--bundles <dir>` reads a local build (public/data), otherwise the live site. */
export async function loadBundle(name, bundlesDir = null) {
  if (bundlesDir) {
    const f = path.join(bundlesDir, name);
    return fs.existsSync(f) ? JSON.parse(fs.readFileSync(f, 'utf8')) : null;
  }
  const r = await fetch(`https://vote.kevinhg.com/data/${name}`);
  return r.ok ? r.json() : null;
}

export function fileStore(dir) {
  fs.mkdirSync(dir, { recursive: true });
  const f = (k) => path.join(dir, `${encodeURIComponent(k)}.txt`);
  return {
    async get(k) { return fs.existsSync(f(k)) ? fs.readFileSync(f(k), 'utf8') : null; },
    async put(k, v) { fs.writeFileSync(f(k), String(v)); },
    async delete(k) { if (fs.existsSync(f(k))) fs.rmSync(f(k)); },
  };
}

export function folderArchive(dir) {
  return { async put(k, v) { const p = path.join(dir, k); fs.mkdirSync(path.dirname(p), { recursive: true }); fs.writeFileSync(p, String(v)); } };
}

export function flags(argv) {
  const out = { _: [] };
  for (let i = 0; i < argv.length; i++) {
    const a = argv[i];
    if (a.startsWith('--')) { const k = a.slice(2); const nx = argv[i + 1]; if (nx && !nx.startsWith('--')) { out[k] = nx; i++; } else out[k] = true; } else out._.push(a);
  }
  return out;
}
